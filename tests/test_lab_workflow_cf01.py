    def prepared(self, masses=True):
        self.counter += 1
        journal = self.stack.enter_context(Journal(self.folder / ('case-%02d.sqlite3' % self.counter)))
        flow = Workflow.create(journal, run_id='SYN.LAB.CF01.TEST%02d' % self.counter)
